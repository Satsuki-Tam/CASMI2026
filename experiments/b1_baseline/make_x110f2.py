"""110 fold-2 replication (110_prereg_fpseed.md section 2: "if fold 1 passes, the same procedure once on fold 2 with two fold-2-held-out models").
Generates the fold-2 copies of the REGISTERED fold-1 readers and job by literal substitution only (paths, hashes, labels), so the fold-2 reading is
the fold-1 procedure unchanged: x110_stage1.py -> x110f2_stage1.py, x110_stage3.py -> x110f2_stage3.py, spark/jobs/spark_x110.sh ->
spark/jobs/spark_x110f2.sh, spark/jobs/x110_stage3_resume.sh -> spark/jobs/x110f2_stage3_resume.sh. The fold-1 files are not modified.
Substitutions are applied in order; no fold-1 token may remain (exit 1 otherwise); review the diff against the fold-1 file. Usage: python make_x110f2.py (repo root or anywhere)."""
import os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SLOT1 = "1739d5683fa94fd73fe3b37db98ac364cb5dfdc22ad5bea9789be9c48d7cadc4"
SLOT2 = "257062cb6ece333226027de6e313792e7b364517adf42a05e0df950b8e27bbe2"   # public fold_safe_fpnet/fpnet_fold2.pt (= fpnet_fold2_as_fold0 slot)
NOTE = ("FOLD-2 REPLICATION, generated by make_x110f2.py from the registered fold-1 file by literal substitution (paths, hashes, labels only); "
        "seed-1 run experiments/fpnet_seed/f2s1, fold-2 slot fpnet_fold2_as_fold0 (sha 257062cb...), tables f2dev / np053f2dev, baseline diag/r102_*f2dev.")
COMMON = [("experiments/fpnet_seed/f1s1", "experiments/fpnet_seed/f2s1"), (SLOT1, SLOT2), ("f1dev", "f2dev"), ("eval_set_f1/", "eval_set_f2/"),
          ("diag/x110_", "diag/x110f2_"), ("diag/r110_", "diag/r110f2_")]
JOBS = {
    "experiments/b1_baseline/x110_stage1.py": ("experiments/b1_baseline/x110f2_stage1.py", COMMON + [
        ("public fpnet_fold1 in the fold-1 slot", "public fpnet_fold2 in the fold-2 slot"), ("fold-1 slot sha 1739d568...", "fold-2 slot sha 257062cb..."), ("fold-1 slot", "fold-2 slot"), ("(fold 1:", "(fold 2:"),
        ("x110_stage1.py", "x110f2_stage1.py")]),
    "experiments/b1_baseline/x110_stage3.py": ("experiments/b1_baseline/x110f2_stage3.py", COMMON + [
        ("r110_{", "r110f2_{"), ("PASS (fold 1) -> fold 2 replication", "PASS (fold-2 replication)"), ("(fold 1)", "(fold 2)"), ("fold 1 only", "fold 2 (replication)"),
        ("X110_FAIL_REPRO", "X110F2_FAIL_REPRO"), ("fold-1", "fold-2"), ("fold 1", "fold 2"), ("x110_stage3.py", "x110f2_stage3.py")]),
    "spark/jobs/spark_x110.sh": ("spark/jobs/spark_x110f2.sh", COMMON + [
        ("fpnet_f1s1", "fpnet_f2s1"), ("F1=data/external/fpnet_fold1_as_fold0", "FK=data/external/fpnet_fold2_as_fold0"),
        ("$F1/", "$FK/"), ("--fold_safe $F1 ", "--fold_safe $FK "), ("$FS/fpnet_fold1.pt", "$FS/fpnet_fold2.pt"), ("structures.parquet $FS 1 >", "structures.parquet $FS 2 >"),
        ("fold-1 slot does not point to the public fpnet_fold1", "fold-2 slot does not point to the public fpnet_fold2"),
        ("x110_stage1.py", "x110f2_stage1.py"), ("x110_stage3.py", "x110f2_stage3.py"), ("spark/jobs/spark_x110.sh", "spark/jobs/spark_x110f2.sh"),
        ("x110_stage3_resume.sh", "x110f2_stage3_resume.sh"), ("X110_", "X110F2_"), ("x110_table_identity", "x110f2_table_identity"),
        ("spark_fold1_sets.sh", "spark_fold2_sets.sh"), ("fold-1", "fold-2"), ("fold 1", "fold 2")]),
    "spark/jobs/x110_stage3_resume.sh": ("spark/jobs/x110f2_stage3_resume.sh", COMMON + [
        ("x110_stage3.py", "x110f2_stage3.py"), ("x110_manifest", "x110f2_manifest"), ("X110_", "X110F2_"), ("x110_stage3_resume.sh", "x110f2_stage3_resume.sh"),
        ("x110_repro_audit", "x110f2_repro_audit")]),
}
LEFT = re.compile(r"f1dev|f1s1|fold1|fold-1|fold 1|eval_set_f1|" + SLOT1[:12] + r"|1739d568|diag/x110_|diag/r110_|X110_(?!F2)|x110_stage")
import hashlib, json
bad = 0; OUTS = {}
for src, (dst, subs) in JOBS.items():
    t = open(os.path.join(ROOT, src), encoding="utf-8").read()
    for a, b in subs:
        t = t.replace(a, b)
    if dst.endswith(".py"):
        t = t.replace('"""', '"""' + NOTE + "\n", 1)
    else:
        t = t.replace("#!/bin/bash\n", "#!/bin/bash\n# " + NOTE + "\n", 1)
    hits = [l for l in t.splitlines() if LEFT.search(l) and "n111/r1" not in l and "generated by make_x110f2.py" not in l]
    if hits:
        print(f"FAIL {dst}: fold-1 tokens remain:"); [print("   ", h[:220]) for h in hits]; bad += 1
    OUTS[dst] = (src, t)
if bad:   # Codex 117: check every output first, write nothing on failure
    print("nothing written"); sys.exit(1)
H = lambda b: hashlib.sha256(b).hexdigest()
rec = dict(generator_sha256=H(open(os.path.abspath(__file__), "rb").read()), files={})
for dst, (src, t) in OUTS.items():
    open(os.path.join(ROOT, dst), "w", encoding="utf-8", newline="\n").write(t)
    rec["files"][dst] = dict(source=src, source_sha256=H(open(os.path.join(ROOT, src), "rb").read()), sha256=H(t.encode("utf-8")))
    print(f"wrote {dst} ({len(t)} chars)")
json.dump(rec, open(os.path.join(ROOT, "experiments/b1_baseline/diag/x110f2_generation.json"), "w"), indent=1)
sys.exit(0)
