"""Derive train_fivefold_win.py from the public train_fivefold.py (dmitriigluzdov/casmi26-fold-safe-fpnet) with the minimum changes needed on
Windows and for the full-data variants, each asserted so the recipe itself is untouched:
  1. multiprocessing 'fork' -> 'spawn' (Windows has no fork);
  2. a spawned worker builds its own traindata.Data (the parent's object is not inherited); the large arrays (spectra CSR, packed pool
     fingerprints) are memory-mapped so the workers share them through the OS page cache;
  3. SIGHUP is only registered where it exists (it does not on Windows);
  4. the input gate understands the 'full_eval' variant written by prep_full_eval.py besides the public fold recipe.
Run with ABSOLUTE --run and --code paths (spawned workers re-import this module after the parent's chdir).
Usage: python make_win_trainer.py <public train_fivefold.py> <out train_fivefold_win.py>
"""
import io, sys
src, dst = sys.argv[1], sys.argv[2]
s = io.open(src, encoding="utf-8").read()   # universal newlines (the public file has CRLF endings)
NL = chr(10)


def sub(old, new, count=1):
    global s
    n = s.count(old)
    assert n == count, (old[:60], n)
    s = s.replace(old, new)


sub("signal.signal(signal.SIGHUP, stop_requested)", "signal.signal(signal.SIGHUP, stop_requested) if hasattr(signal, 'SIGHUP') else None")
sub("    signal.signal(signal.SIGHUP, signal.SIG_DFL)" + NL, "    if hasattr(signal, 'SIGHUP'): signal.signal(signal.SIGHUP, signal.SIG_DFL)" + NL)
WORKER_DATA = NL.join([
    "    D = G.get('D')",
    "    if D is None:   # [win] spawned worker: build the data object here, large arrays memory-mapped (shared via the OS page cache)",
    "        _load = np.load",
    "        def _mm(f, *a_, **k_):",
    "            if str(f).replace(chr(92), '/').endswith(('spec_mz.npy', 'spec_it.npy', 'spec_off.npy', 'pool_fp.npy')) and 'mmap_mode' not in k_:",
    "                k_['mmap_mode'] = 'r'",
    "            return _load(f, *a_, **k_)",
    "        np.load = _mm",
    "        try:",
    "            import warnings; warnings.filterwarnings('ignore', message='The given NumPy array is not writable')",
    "            D = traindata.Data('cpu', seed=args.seed, holdout_folds=tuple(args.holdout.split(',')))",
    "        finally:",
    "            np.load = _load",
    "        G['D'] = D",
    ""])
sub("    D = G['D']" + NL, WORKER_DATA)
sub("mp.get_context('fork')", "mp.get_context('spawn')", count=2)
GATE_OLD = "    assert gate['passed'] and gate['panel_training_overlap']==0 and gate['fold_training_overlap']==0" + NL
GATE_NEW = NL.join([
    "    if gate.get('recipe_variant') in ('full_eval', 'full_rk'):   # [win] recipe-aware gate: no held fold; query acquisitions removed; identity-group holdouts",
    "        assert gate['passed'] and gate['panel_query_rows_in_training']==0 and gate['holdout_training_overlap']==0",
    "    else:",
    "        assert gate['passed'] and gate['panel_training_overlap']==0 and gate['fold_training_overlap']==0",
    ""])
sub(GATE_OLD, GATE_NEW)
s = s.replace('"""Fold-safe training', '"""[win] Windows variant generated by experiments/fpnet_full/make_win_trainer.py (fork->spawn, per-worker memory-mapped data, SIGHUP guard, recipe-aware gate).' + NL + 'Fold-safe training', 1)
io.open(dst, "w", encoding="utf-8", newline=NL).write(s)
print("wrote", dst)
